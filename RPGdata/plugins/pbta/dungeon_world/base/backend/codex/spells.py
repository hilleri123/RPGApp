    def spells_map(self) -> dict[str, Spell]:
        return {s.id: s for s in self.get_spells()}

    def spell_books_map(self) -> dict[str, SpellBook]:
        return {b.id: b for b in self.get_spell_books()}

    def spells_for_class(self, class_id: str) -> list[Spell]:
        return [s for s in self.get_spells() if class_id in (s.classes or [])]

