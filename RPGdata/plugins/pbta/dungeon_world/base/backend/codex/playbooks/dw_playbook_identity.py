from plugins.pbta.base.backend.types import (
    Move,
    Playbook,
    PlaybookAlignmentOption,
    PlaybookRaceOption,
)


def _race_move(move_id: str, title: str, effect: str, summary: str = "") -> Move:
    return Move(
        id=move_id,
        title=title,
        kind="race",
        available_stats=[],
        requires_roll=False,
        summary=summary or effect[:120],
        trigger="",
        effect=effect,
        effect_10_plus="",
        effect_7_9="",
        effect_6_minus="",
    )


def _align(aid: str, title: str, summary: str) -> PlaybookAlignmentOption:
    return PlaybookAlignmentOption(id=aid, title=title, summary=summary)


def _race(rid: str, title: str, move_id: str) -> PlaybookRaceOption:
    return PlaybookRaceOption(id=rid, title=title, move_id=move_id)


