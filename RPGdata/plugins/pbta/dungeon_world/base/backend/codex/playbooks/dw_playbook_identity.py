def apply_playbook_identity(pb: Playbook) -> Playbook:
    meta = PLAYBOOK_IDENTITY.get(pb.id)
    if not meta:
        return pb
    return pb.model_copy(
        update={
            "races": meta["races"],
            "alignments": meta["alignments"],
        },
    )
